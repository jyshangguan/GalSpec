def combined_html(bodies: dict, title: str, css: str) -> str:
    """All four pages in one self-contained document, with anchor navigation.

    Cross-document links do not work everywhere a report gets opened (sandboxed
    preview panes and ``srcdoc`` iframes block them, so clicking a nav item looks
    like nothing happens).  In-page anchors always work, and a single file is also
    what you want when the report is e-mailed or attached to a paper draft.
    """
    nav = "".join(f'<a href="#{key}">{label}</a>' for key, label, _ in SECTIONS)
    parts = []
    for key, label, blurb in SECTIONS:
        body = bodies.get(key, "")
        # the individual pages link to each other; point those links at our own sections
        for other, _, _ in SECTIONS:
            body = body.replace(f'href="{other}.html"', f'href="#{other}"')
        body = body.replace('href="index.html"', 'href="#overview"')
        # jump straight to the term; the glossary's item ids are in this document
        body = re.sub(r'href="glossary\.html#([^"]+)"', r'href="#\1"', body)
        body = body.replace('href="glossary.html"', 'href="#glossary"')
        parts.append(
            f'<section id="{key}">\n'
            f'<h1 class="section-title">{label} <span class="blurb">&mdash; {blurb}</span></h1>\n'
            f'{body}\n</section>')
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<style>
{css}
</style>
</head>
<body>
<header class="sticky">
<nav class="toc">{nav}</nav>
</header>
<main>
{chr(10).join(parts)}
</main>
<footer>
<p>Generated by <code>develop/dev_jax/make_report.py</code>. Machine: one RTX 4090 GPU and a
192-core x86 host. All numbers in this report were measured, and every figure is embedded in
this file.</p>
</footer>
</body>
</html>
"""


def fmt(value, digits=3):
    if value is None:
        return "&mdash;"
    if isinstance(value, (int, np.integer)):
        return f"{value}"
    return f"{value:.{digits}f}"


def factor(value):
    return f"{value:.1f}&times;"


