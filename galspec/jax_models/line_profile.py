"""JAX emission/absorption line profiles.

These mirror the CPU classes in :mod:`galspec.line_profile` one-for-one,
including their default bounds, so priors generated by
:class:`galspec.jnesty_fit.JNesty_Fit` match those of ``Dynesty_Fit``.

Multi-component models (``Line_MultiGauss``, ``Line_MultiGauss_doublet``)
build their parameter list from ``n_components`` exactly like the CPU version,
and the wind components keep the CPU convention that amplitudes are *relative*
to the core amplitude.
"""

from __future__ import annotations

from typing import Optional, Sequence

import jax.numpy as jnp
import numpy as np

from ..constants import ls_km
from .core import JaxModel, ParamSpec
from .functional import velocity

__all__ = [
    "Line_Gaussian",
    "Line_GaussHermite",
    "Line_GaussHermite_doublet",
    "Line_MultiGauss",
    "Line_MultiGauss_doublet",
    "Line_Absorption",
    "Line_Absorption_doublet",
    "Line_template",
    "Line_Exponential",
]


class Line_Gaussian(JaxModel):
    """Gaussian line profile in velocity units -- ``galspec.Line_Gaussian``."""

    model_kind = "Line_Gaussian"
    PARAMS = (
        ParamSpec("amplitude", 1.0, bounds=(0.0, None)),
        ParamSpec("dv", 0.0, bounds=(-2000.0, 2000.0)),
        ParamSpec("sigma", 200.0, bounds=(20.0, 10000.0)),
        ParamSpec("wavec", 5000.0, fixed=True),
    )

    def evaluate(self, x, p):
        v = velocity(x, p["wavec"])
        return p["amplitude"] * jnp.exp(-0.5 * ((v - p["dv"]) / p["sigma"]) ** 2)


class Line_GaussHermite(JaxModel):
    """4th-order Gauss-Hermite profile -- ``galspec.Line_GaussHermite``."""

    model_kind = "Line_GaussHermite"
    PARAMS = (
        ParamSpec("amplitude", 1.0, bounds=(0.0, None)),
        ParamSpec("dv", 0.0, bounds=(-2000.0, 2000.0)),
        ParamSpec("sigma", 200.0, bounds=(20.0, 10000.0)),
        ParamSpec("h3", 0.0, bounds=(-0.4, 0.4)),
        ParamSpec("h4", 0.0, bounds=(-0.4, 0.4)),
        ParamSpec("wavec", 5000.0, fixed=True),
    )

    def __init__(self, clip: bool = True, name: Optional[str] = None,
                 fixed: Optional[dict] = None, bounds: Optional[dict] = None, **kwargs):
        self.clip = bool(clip)
        super().__init__(name=name, fixed=fixed, bounds=bounds, **kwargs)

    def evaluate(self, x, p):
        v = velocity(x, p["wavec"])
        w = (v - p["dv"]) / p["sigma"]

        g = p["amplitude"] * jnp.exp(-0.5 * w ** 2)
        h3 = (2.0 * w ** 3 - 3.0 * w) / 3.0 ** 0.5
        h4 = (4.0 * w ** 4 - 12.0 * w ** 2 + 3.0) / 24.0 ** 0.5
        f = g * (1.0 + p["h3"] * h3 + p["h4"] * h4)
        return jnp.where(f < 0.0, 0.0, f) if self.clip else f


class Line_GaussHermite_doublet(JaxModel):
    """Gauss-Hermite doublet -- ``galspec.Line_GaussHermite_doublet``."""

    model_kind = "Line_GaussHermite_doublet"
    PARAMS = (
        ParamSpec("amp_c0", 1.0, bounds=(0.0, None)),
        ParamSpec("amp_c1", 1.0, bounds=(0.0, None)),
        ParamSpec("dv_c", 0.0, bounds=(-2000.0, 2000.0)),
        ParamSpec("sigma_c", 200.0, bounds=(20.0, 10000.0)),
        ParamSpec("h3", 0.0, bounds=(-0.4, 0.4)),
        ParamSpec("h4", 0.0, bounds=(-0.4, 0.4)),
        ParamSpec("wavec0", 5000.0, fixed=True),
        ParamSpec("wavec1", 5000.0, fixed=True),
    )

    def __init__(self, clip: bool = True, name: Optional[str] = None,
                 fixed: Optional[dict] = None, bounds: Optional[dict] = None, **kwargs):
        self.clip = bool(clip)
        super().__init__(name=name, fixed=fixed, bounds=bounds, **kwargs)

    @staticmethod
    def _component(x, amp, dv, sigma, h3, h4, wavec):
        w = (velocity(x, wavec) - dv) / sigma
        g = amp * jnp.exp(-0.5 * w ** 2)
        g3 = (2.0 * w ** 3 - 3.0 * w) / 3.0 ** 0.5
        g4 = (4.0 * w ** 4 - 12.0 * w ** 2 + 3.0) / 24.0 ** 0.5
        return g * (1.0 + h3 * g3 + h4 * g4)

    def evaluate(self, x, p):
        f = (self._component(x, p["amp_c0"], p["dv_c"], p["sigma_c"], p["h3"], p["h4"], p["wavec0"])
             + self._component(x, p["amp_c1"], p["dv_c"], p["sigma_c"], p["h3"], p["h4"], p["wavec1"]))
        return jnp.where(f < 0.0, 0.0, f) if self.clip else f


class Line_MultiGauss(JaxModel):
    """Core + wind Gaussian components -- ``galspec.Line_MultiGauss``.

    Wind amplitudes are relative to the core amplitude, matching the CPU model.
    """

    model_kind = "Line_MultiGauss"

    def __init__(self, n_components: int = 1, par_w: Optional[dict] = None,
                 name: Optional[str] = None, fixed: Optional[dict] = None,
                 bounds: Optional[dict] = None, **kwargs):
        n_components = int(n_components)
        if n_components < 1:
            raise ValueError("n_components must be positive")
        self.n_components = n_components

        specs = [
            ParamSpec("amp_c", 1.0, bounds=(0.0, None)),
            ParamSpec("dv_c", 0.0, bounds=(-2000.0, 2000.0)),
            ParamSpec("sigma_c", 200.0, bounds=(20.0, 10000.0)),
            ParamSpec("wavec", 5000.0, fixed=True),
        ]
        for i in range(n_components - 1):
            specs.extend([
                ParamSpec(f"amp_w{i}", 0.0, bounds=(0.0, 1.0)),
                ParamSpec(f"dv_w{i}", 0.0, bounds=(-8000.0, 8000.0)),
                ParamSpec(f"sigma_w{i}", 0.0, bounds=(0.0, 10000.0)),
            ])
        self._param_specs = tuple(specs)

        # CPU models accept `par_w={'amp_w0': ...}` in addition to **kwargs.
        for key, value in dict(par_w or {}).items():
            if key in kwargs:
                raise TypeError(f"{key!r} passed both directly and via par_w")
            kwargs[key] = value
        super().__init__(name=name, fixed=fixed, bounds=bounds, **kwargs)

    @property
    def PARAMS(self):  # type: ignore[override]
        return self._param_specs

    def _static_init(self) -> None:
        # The CPU models default every wind sigma to the core sigma.
        for i in range(self.n_components - 1):
            name = f"sigma_w{i}"
            if name not in self._provided:
                self._values[name] = self._values["sigma_c"]

    def evaluate(self, x, p):
        v = velocity(x, p["wavec"])
        flux = p["amp_c"] * jnp.exp(-0.5 * ((v - p["dv_c"]) / p["sigma_c"]) ** 2)
        for i in range(self.n_components - 1):
            flux = flux + p["amp_c"] * p[f"amp_w{i}"] * jnp.exp(
                -0.5 * ((v - p["dv_c"] - p[f"dv_w{i}"]) / p[f"sigma_w{i}"]) ** 2)
        return flux


class Line_MultiGauss_doublet(JaxModel):
    """Doublet with core + wind Gaussian components -- ``galspec.Line_MultiGauss_doublet``."""

    model_kind = "Line_MultiGauss_doublet"

    def __init__(self, n_components: int = 1, par_w: Optional[dict] = None,
                 name: Optional[str] = None, fixed: Optional[dict] = None,
                 bounds: Optional[dict] = None, **kwargs):
        n_components = int(n_components)
        if n_components < 1:
            raise ValueError("n_components must be positive")
        self.n_components = n_components

        specs = [
            ParamSpec("amp_c0", 1.0, bounds=(0.0, None)),
            ParamSpec("amp_c1", 1.0, bounds=(0.0, None)),
            ParamSpec("dv_c", 0.0, bounds=(-2000.0, 2000.0)),
            ParamSpec("sigma_c", 200.0, bounds=(20.0, 10000.0)),
            ParamSpec("wavec0", 5000.0, fixed=True),
            ParamSpec("wavec1", 5000.0, fixed=True),
        ]
        for i in range(n_components - 1):
            specs.extend([
                ParamSpec(f"amp_w{i}", 0.0, bounds=(0.0, 1.0)),
                ParamSpec(f"dv_w{i}", 0.0, bounds=(-2000.0, 2000.0)),
                ParamSpec(f"sigma_w{i}", 0.0, bounds=(0.0, 10000.0)),
            ])
        self._param_specs = tuple(specs)

        for key, value in dict(par_w or {}).items():
            if key in kwargs:
                raise TypeError(f"{key!r} passed both directly and via par_w")
            kwargs[key] = value
        super().__init__(name=name, fixed=fixed, bounds=bounds, **kwargs)

    @property
    def PARAMS(self):  # type: ignore[override]
        return self._param_specs

    def _static_init(self) -> None:
        # The CPU models default every wind sigma to the core sigma.
        for i in range(self.n_components - 1):
            name = f"sigma_w{i}"
            if name not in self._provided:
                self._values[name] = self._values["sigma_c"]

    def evaluate(self, x, p):
        v0 = velocity(x, p["wavec0"])
        v1 = velocity(x, p["wavec1"])
        sigma = p["sigma_c"]
        dv = p["dv_c"]

        flux = (p["amp_c0"] * jnp.exp(-0.5 * ((v0 - dv) / sigma) ** 2)
                + p["amp_c1"] * jnp.exp(-0.5 * ((v1 - dv) / sigma) ** 2))

        for i in range(self.n_components - 1):
            amp = p[f"amp_w{i}"]
            dv_w = dv + p[f"dv_w{i}"]
            sigma_w = p[f"sigma_w{i}"]
            flux = flux + (p["amp_c0"] * amp * jnp.exp(-0.5 * ((v0 - dv_w) / sigma_w) ** 2)
                           + p["amp_c1"] * amp * jnp.exp(-0.5 * ((v1 - dv_w) / sigma_w) ** 2))
        return flux


class Line_Absorption(JaxModel):
    """Absorption line with covering fraction -- ``galspec.Line_Absorption``."""

    model_kind = "Line_Absorption"
    PARAMS = (
        ParamSpec("logtau0", 0.0, bounds=(-2.0, 2.0)),
        ParamSpec("dv", 0.0, bounds=(-10000.0, 10000.0)),
        ParamSpec("sigma", 200.0, bounds=(20.0, 10000.0)),
        ParamSpec("Cf", 1.0, bounds=(0.0, 1.0)),
        ParamSpec("wavec", 5000.0, fixed=True),
    )

    def evaluate(self, x, p):
        v = velocity(x, p["wavec"])
        tau = 10.0 ** p["logtau0"] * jnp.exp(-0.5 * ((v - p["dv"]) / p["sigma"]) ** 2)
        return 1.0 - p["Cf"] + p["Cf"] * jnp.exp(-tau)


class Line_Absorption_doublet(JaxModel):
    """Absorption doublet -- ``galspec.Line_Absorption_doublet``."""

    model_kind = "Line_Absorption_doublet"
    PARAMS = (
        ParamSpec("logtau0", 0.0, bounds=(-2.0, 2.0)),
        ParamSpec("logtau1", 0.0, bounds=(-2.0, 2.0)),
        ParamSpec("dv", 0.0, bounds=(-10000.0, 10000.0)),
        ParamSpec("sigma", 200.0, bounds=(20.0, 10000.0)),
        ParamSpec("Cf", 1.0, bounds=(0.0, 1.0)),
        ParamSpec("wavec0", 5000.0, fixed=True),
        ParamSpec("wavec1", 5100.0, fixed=True),
    )

    def evaluate(self, x, p):
        v0 = velocity(x, p["wavec0"])
        v1 = velocity(x, p["wavec1"])
        sigma = p["sigma"]
        tau0 = 10.0 ** p["logtau0"] * jnp.exp(-0.5 * ((v0 - p["dv"]) / sigma) ** 2)
        tau1 = 10.0 ** p["logtau1"] * jnp.exp(-0.5 * ((v1 - p["dv"]) / sigma) ** 2)
        return ((1.0 - p["Cf"] + p["Cf"] * jnp.exp(-tau0))
                * (1.0 - p["Cf"] + p["Cf"] * jnp.exp(-tau1)))


class Line_template(JaxModel):
    """Line profile from a tabulated velocity template -- ``galspec.Line_template``.

    Parameters
    ----------
    template_velc : array_like
        Template velocity grid [km/s].
    template_flux : array_like
        Template flux at ``template_velc`` (arbitrary units).
    """

    model_kind = "Line_template"
    PARAMS = (
        ParamSpec("amplitude", 1.0, bounds=(0.0, None)),
        ParamSpec("dv", 0.0, bounds=(-2000.0, 2000.0)),
        ParamSpec("wavec", 5000.0, fixed=True),
    )

    def __init__(self, template_velc: Sequence[float], template_flux: Sequence[float],
                 name: Optional[str] = None, fixed: Optional[dict] = None,
                 bounds: Optional[dict] = None, **kwargs):
        velc = np.asarray(template_velc, dtype=float)
        flux = np.asarray(template_flux, dtype=float)
        if velc.shape != flux.shape or velc.ndim != 1:
            raise ValueError("template_velc and template_flux must be 1-D of equal length")
        order = np.argsort(velc)
        self._template_velc = jnp.asarray(velc[order])
        self._template_flux = jnp.asarray(flux[order])
        self._vmin = float(velc[order][0])
        self._vmax = float(velc[order][-1])
        super().__init__(name=name, fixed=fixed, bounds=bounds, **kwargs)

    def evaluate(self, x, p):
        v = velocity(x, p["wavec"]) - p["dv"]
        inside = (v >= self._vmin) & (v <= self._vmax)
        flux = p["amplitude"] * jnp.interp(v, self._template_velc, self._template_flux)
        return jnp.where(inside, flux, 0.0)


class Line_Exponential(JaxModel):
    """Exponential profile smoothed by its Gaussian kernel -- ``galspec.Line_Exponential``.

    The CPU model smooths ``amplitude * exp(-|(v - dv)/w|)`` with
    ``gaussian_filter1d(..., sigma / dv_pixel)`` where ``dv_pixel`` is the
    velocity width of one wavelength pixel.  A static kernel radius is required
    under ``jit``, hence ``sigma_pix_max`` (see :meth:`prepare`).
    """

    model_kind = "Line_Exponential"
    PARAMS = (
        ParamSpec("amplitude", 1.0, bounds=(0.0, None)),
        ParamSpec("dv", 0.0, bounds=(-2000.0, 2000.0)),
        ParamSpec("sigma", 200.0, bounds=(20.0, 10000.0)),
        ParamSpec("w", 100.0, bounds=(1.0, 1000.0)),
        ParamSpec("wavec", 5000.0, fixed=True),
    )

    def __init__(self, sigma_pix_max: float = 500.0, name: Optional[str] = None,
                 fixed: Optional[dict] = None, bounds: Optional[dict] = None, **kwargs):
        self.sigma_pix_max = float(sigma_pix_max)
        self._radius = int(4.0 * self.sigma_pix_max + 0.5)
        super().__init__(name=name, fixed=fixed, bounds=bounds, **kwargs)

    def prepare(self, x) -> None:
        """Store the wavelength pixel scale used for the velocity conversion."""
        xv = np.asarray(x, dtype=float)
        self._dx = float(np.median(np.diff(xv)))

    def evaluate(self, x, p):
        from .functional import gaussian_smooth1d

        dx = getattr(self, "_dx", None)
        if dx is None:
            raise RuntimeError(
                "Line_Exponential requires prepare(wave) before evaluation so that the "
                "velocity-per-pixel scale is known")
        v = velocity(x, p["wavec"])
        f_exp = p["amplitude"] * jnp.exp(-jnp.abs((v - p["dv"]) / p["w"]))
        dv_pix = dx / p["wavec"] * ls_km
        return gaussian_smooth1d(f_exp, p["sigma"] / dv_pix, radius=self._radius)